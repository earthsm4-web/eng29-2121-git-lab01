"""Verified ngspice adapter for Common-Emitter Voltage Divider v1.

Generates a SPICE netlist, runs ngspice via subprocess (.op / .ac / .tran),
checks the output, and parses results into easy-to-read structures with units.

All numeric values come from the real ngspice solver -- no mock data.
"""

from __future__ import annotations

import math
import os
import shutil
import subprocess
import tempfile
from dataclasses import dataclass, field
from typing import Any


NGSPICE_BIN = r"C:\tools\ngspice-47\Spice64\bin\ngspice_con.exe"
DEFAULT_TIMEOUT_SECONDS = 60


class SpiceEngineError(RuntimeError):
    """Raised when the SPICE engine cannot run or produce valid output."""


@dataclass(frozen=True)
class SpiceParams:
    """Validated SI-unit inputs for CE Voltage Divider v1."""

    vcc: float          # V
    rc: float           # ohm
    r1: float           # ohm
    r2: float           # ohm
    re: float           # ohm
    rl: float           # ohm (load resistor)
    beta: float         # dimensionless
    vbe: float          # V
    source_ampl: float  # V (peak amplitude of input source)
    source_freq: float  # Hz


@dataclass(frozen=True)
class SpiceOpResult:
    """DC Operating Point (.op) results from ngspice."""

    vb: float   # V
    ve: float   # V
    vc: float   # V
    vce: float  # V
    ic: float   # A
    ib: float   # A
    ie: float   # A
    region: str  # "active" | "saturation" | "cutoff"
    netlist: str
    run_log: str


@dataclass(frozen=True)
class SpiceAcResult:
    """AC Analysis (.ac) results from ngspice."""

    frequency: list[float]   # Hz
    gain_db: list[float]     # dB  (20*log10(|Vout/Vin|))
    phase_deg: list[float]   # degrees
    netlist: str
    run_log: str


@dataclass(frozen=True)
class SpiceTranResult:
    """Transient Analysis (.tran) results from ngspice."""

    time: list[float]    # seconds
    vin: list[float]     # V
    vout: list[float]    # V
    netlist: str
    run_log: str


def _check_ngspice_available() -> str:
    """Return the ngspice binary path, or raise if not found."""
    if os.path.exists(NGSPICE_BIN):
        return NGSPICE_BIN
    fallback = shutil.which("ngspice") or shutil.which("ngspice_con")
    if fallback:
        return fallback
    raise SpiceEngineError(
        "ngspice binary not found. Expected at "
        f"{NGSPICE_BIN} or on PATH. Install ngspice and try again."
    )


def _build_netlist(p: SpiceParams, analysis: str) -> str:
    """Build a CE Voltage Divider v1 netlist for the given analysis type.

    Topology (single-supply CE):
        VCC --- R1 ---+--- R2 --- GND
                      |
                     Base(Q1)
        VCC --- RC ---+--- Collector(Q1)
                      |
        Emitter(Q1) --- RE --- GND
        Collector --- Cout ---+--- RL --- GND
                              |
                             Vout
        Vin --- Cin --- Base(Q1)
    """
    lines: list[str] = [
        "* CE Voltage Divider v1 -- generated by transistor-simulator Lab 4",
        "* All resistances in ohms, voltages in volts, frequencies in Hz.",
        f"* VCC={p.vcc} RC={p.rc} R1={p.r1} R2={p.r2} RE={p.re} RL={p.rl}",
        f"* Beta={p.beta} VBE={p.vbe} Src={p.source_ampl}V @ {p.source_freq}Hz",
        "",
        "VCC 1 0 DC {vcc}".format(vcc=p.vcc),
        "VIN 2 0 SIN(0 {ampl} {freq}) AC {ampl}".format(ampl=p.source_ampl, freq=p.source_freq),
        "R1 1 3 {r1}".format(r1=p.r1),
        "R2 3 0 {r2}".format(r2=p.r2),
        "RC 1 4 {rc}".format(rc=p.rc),
        "RE 5 0 {re}".format(re=p.re),
        "CIN 2 3 10u",      # input coupling capacitor (10 uF)
        "COUT 4 6 10u",     # output coupling capacitor (10 uF)
        "RL 6 0 {rl}".format(rl=p.rl),
        "Q1 4 3 5 QNPN",
        "",
        ".model QNPN NPN(IS=1e-14 BF={beta})".format(beta=p.beta),
        "",
    ]

    if analysis == "op":
        lines.extend([".op"])
    elif analysis == "ac":
        lines.extend([
            ".ac dec 10 1 1e6",
            ".print ac vm(6) vm(2) vp(6) vp(2)",
        ])
    elif analysis == "tran":
        # 5 cycles of the source frequency, 1000 points
        tstop = 5.0 / p.source_freq if p.source_freq > 0 else 0.005
        tstep = tstop / 1000.0
        lines.extend([
            ".tran {tstop} {tstep}".format(tstop=tstop, tstep=tstep),
            ".print tran v(2) v(6)",
        ])
    else:
        raise SpiceEngineError(f"Unknown analysis type: {analysis}")

    lines.append(".end")
    return "\n".join(lines)


def _run_ngspice(netlist: str, analysis: str) -> tuple[str, str, str]:
    """Run ngspice with the netlist. Returns (stdout, stderr, run_log).

    The ``-r`` option is intentionally omitted so that ngspice prints the
    ``.print`` results to stdout instead of writing a binary raw file.
    """
    binary = _check_ngspice_available()

    with tempfile.TemporaryDirectory(prefix="spice_sim_") as tmpdir:
        netlist_path = os.path.join(tmpdir, "circuit.cir")

        with open(netlist_path, "w", encoding="utf-8") as f:
            f.write(netlist)

        stdout_path = os.path.join(tmpdir, f"{analysis}_output.txt")
        try:
            proc = subprocess.run(
                [binary, "-b", netlist_path],
                capture_output=True,
                text=True,
                timeout=DEFAULT_TIMEOUT_SECONDS,
            )
        except subprocess.TimeoutExpired as exc:
            raise SpiceEngineError(
                f"ngspice timed out after {DEFAULT_TIMEOUT_SECONDS} seconds "
                f"during {analysis} analysis."
            ) from exc
        except FileNotFoundError as exc:
            raise SpiceEngineError(
                f"ngspice binary not executable: {binary}"
            ) from exc

        run_log = proc.stdout
        if proc.stderr:
            run_log += "\n--- STDERR ---\n" + proc.stderr

        # Persist stdout as an output artifact and verify it before parsing.
        with open(stdout_path, "w", encoding="utf-8", errors="replace") as f:
            f.write(proc.stdout)
        if not os.path.exists(stdout_path) or os.path.getsize(stdout_path) == 0:
            raise SpiceEngineError(
                f"ngspice output file was not created or is empty for {analysis} analysis.\n"
                f"Run log:\n{run_log}"
            )

        if proc.returncode != 0:
            raise SpiceEngineError(
                f"ngspice exited with code {proc.returncode} during {analysis} analysis.\n"
                f"Run log:\n{run_log}"
            )

        return proc.stdout, proc.stderr, run_log


def _parse_op_output(stdout: str) -> dict[str, float]:
    """Parse ngspice .op output from stdout.

    ngspice prints (without -r) a node-voltage table and per-device
    details.  We capture node names like V(3), V(5), V(4) and BJT device
    currents ic/ib/ie from the ``BJT: Bipolar Junction Transistor`` block.
    """
    values: dict[str, float] = {}
    for line in stdout.splitlines():
        line = line.strip()
        if not line or line.startswith("*"):
            continue
        parts = line.split()
        if len(parts) >= 2:
            name = parts[0]
            # Node voltages: V(3), V(5), V(4), ...
            # BJT device currents: ic, ib, ie (standalone tokens)
            if ("(" in name and ")" in name) or name in ("ic", "ib", "ie"):
                try:
                    values[name.lower()] = float(parts[1])
                except ValueError:
                    continue
    return values


def run_op(p: SpiceParams) -> SpiceOpResult:
    """Run DC Operating Point (.op) analysis and return parsed results."""
    netlist = _build_netlist(p, "op")
    stdout, stderr, run_log = _run_ngspice(netlist, "op")
    vals = _parse_op_output(stdout)

    vb = vals.get("v(3)", 0.0)
    ve = vals.get("v(5)", 0.0)
    vc = vals.get("v(4)", 0.0)
    ic = abs(vals.get("ic", 0.0))   # collector current from BJT device
    ib = abs(vals.get("ib", 0.0))   # base current from BJT device
    ie = abs(vals.get("ie", 0.0))   # emitter current from BJT device
    vce = vc - ve

    # Classify region from computed values
    if vb <= p.vbe:
        region = "cutoff"
    elif vce < 0.2:
        region = "saturation"
    else:
        region = "active"

    return SpiceOpResult(
        vb=vb, ve=ve, vc=vc, vce=vce, ic=ic, ib=ib, ie=ie,
        region=region, netlist=netlist, run_log=run_log,
    )


def _clean_float(token: str) -> float | None:
    """Convert a token like '1.234e+00,' to float, or None if not numeric."""
    token = token.strip().rstrip(",").strip()
    if not token or token in ("-", "+"):
        return None
    try:
        return float(token)
    except ValueError:
        return None


def _is_data_line(line: str) -> bool:
    """True if the line starts with an index number followed by data."""
    stripped = line.strip()
    if not stripped or stripped.startswith("*") or stripped.startswith("Index"):
        return False
    if set(stripped) <= set("-: "):
        return False
    parts = stripped.split()
    if not parts:
        return False
    try:
        int(parts[0])
        return True
    except ValueError:
        return False


def run_ac(p: SpiceParams) -> SpiceAcResult:
    """Run AC Analysis (.ac) and return parsed frequency response.

    ngspice prints magnitude and phase in separate tables.  We scan the
    output for the ``vm(6)`` header (magnitude table) and ``vp(6)`` header
    (phase table), read rows until the next dashed separator, then match by
    frequency.
    """
    netlist = _build_netlist(p, "ac")
    stdout, stderr, run_log = _run_ngspice(netlist, "ac")

    lines = stdout.splitlines()
    mag_data: dict[float, tuple[float, float]] = {}  # freq -> (vm6, vm2)
    phase_data: dict[float, tuple[float, float]] = {}  # freq -> (vp6, vp2)

    i = 0
    while i < len(lines):
        line = lines[i]
        if "vm(6)" in line:
            # magnitude section: read rows until next separator
            i += 1
            # skip separator/blank lines after header
            while i < len(lines) and set(lines[i].strip()) <= set("-: "):
                i += 1
            while i < len(lines):
                l = lines[i]
                if set(l.strip()) <= set("-: "):
                    break
                if _is_data_line(l):
                    parts = l.split()
                    if len(parts) >= 4:
                        try:
                            freq = float(parts[1])
                            v1 = _clean_float(parts[2])
                            v2 = _clean_float(parts[3])
                            if freq is not None and v1 is not None and v2 is not None:
                                mag_data[freq] = (v1, v2)
                        except (ValueError, IndexError):
                            pass
                i += 1
        elif "vp(6)" in line:
            # phase section: read rows until next separator
            i += 1
            # skip separator/blank lines after header
            while i < len(lines) and set(lines[i].strip()) <= set("-: "):
                i += 1
            while i < len(lines):
                l = lines[i]
                if set(l.strip()) <= set("-: "):
                    break
                if _is_data_line(l):
                    parts = l.split()
                    if len(parts) >= 4:
                        try:
                            freq = float(parts[1])
                            v1 = _clean_float(parts[2])
                            v2 = _clean_float(parts[3])
                            if freq is not None and v1 is not None and v2 is not None:
                                phase_data[freq] = (v1, v2)
                        except (ValueError, IndexError):
                            pass
                i += 1
        else:
            i += 1

    # Match by frequency: gain from magnitude table, phase from phase table.
    frequency: list[float] = []
    gain_db: list[float] = []
    phase_deg: list[float] = []

    for freq in sorted(mag_data.keys()):
        vm6, vm2 = mag_data[freq]
        if vm2 <= 0 or vm6 <= 0:
            continue
        frequency.append(freq)
        gain_db.append(20.0 * math.log10(vm6 / vm2))
        if freq in phase_data:
            vp6, vp2 = phase_data[freq]
            phase_deg.append(vp6 - vp2)
        else:
            phase_deg.append(0.0)

    if not frequency:
        raise SpiceEngineError(
            "ngspice AC analysis produced no parseable frequency points.\n"
            f"Run log:\n{run_log}"
        )

    return SpiceAcResult(
        frequency=frequency, gain_db=gain_db, phase_deg=phase_deg,
        netlist=netlist, run_log=run_log,
    )


def run_tran(p: SpiceParams) -> SpiceTranResult:
    """Run Transient Analysis (.tran) and return parsed waveforms.

    ngspice prints: Index   time      v(2)     v(6)
    with comma-separated values.  Column 1 is time, column 2 is v(2) (Vin),
    column 3 is v(6) (Vout).
    """
    netlist = _build_netlist(p, "tran")
    stdout, stderr, run_log = _run_ngspice(netlist, "tran")

    time: list[float] = []
    vin: list[float] = []
    vout: list[float] = []

    for line in stdout.splitlines():
        if not _is_data_line(line):
            continue
        parts = line.split()
        if len(parts) < 4:
            continue
        try:
            t = _clean_float(parts[1])
            v_in = _clean_float(parts[2])
            v_out = _clean_float(parts[3])
        except (ValueError, IndexError):
            continue
        if t is None or v_in is None or v_out is None:
            continue
        time.append(t)
        vin.append(v_in)
        vout.append(v_out)

    if not time:
        raise SpiceEngineError(
            "ngspice Transient analysis produced no parseable time points.\n"
            f"Run log:\n{run_log}"
        )

    return SpiceTranResult(
        time=time, vin=vin, vout=vout,
        netlist=netlist, run_log=run_log,
    )
